def rejection_reason(error):
    if len(error.args) != 1 or type(error.args[0]) is not str:
        return "unknown"
    code = hashlib.sha256(error.args[0].encode("utf-8")).hexdigest()[:16]
    return code if code in _REJECTION_CODES else "unknown"
